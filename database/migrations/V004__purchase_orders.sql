BEGIN;

CREATE TABLE supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    tax_id VARCHAR(40),
    contact_info VARCHAR(200),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE purchase_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES supplier(id),
    status VARCHAR(20) NOT NULL,
    notes TEXT,
    created_by_user_id BIGINT NULL REFERENCES user_account(id),
    created_by_username VARCHAR(80) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_purchase_order_status
        CHECK (status IN ('PENDING', 'PARTIAL', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE purchase_order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_order(id),
    product_id VARCHAR(64) NOT NULL REFERENCES beer_product(id),
    ordered_baskets INTEGER NOT NULL,
    ordered_loose_units INTEGER NOT NULL,
    units_per_basket_snapshot INTEGER NOT NULL,
    ordered_equivalent_units INTEGER NOT NULL,
    received_equivalent_units INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_purchase_order_line_baskets CHECK (ordered_baskets >= 0),
    CONSTRAINT ck_purchase_order_line_loose_units CHECK (ordered_loose_units >= 0),
    CONSTRAINT ck_purchase_order_line_capacity CHECK (units_per_basket_snapshot > 0),
    CONSTRAINT ck_purchase_order_line_ordered CHECK (ordered_equivalent_units > 0),
    CONSTRAINT ck_purchase_order_line_received
        CHECK (received_equivalent_units >= 0 AND received_equivalent_units <= ordered_equivalent_units)
);

CREATE TABLE goods_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_order(id),
    idempotency_key VARCHAR(64) NOT NULL,
    received_by_user_id BIGINT NULL REFERENCES user_account(id),
    received_by_username VARCHAR(80) NOT NULL,
    notes TEXT,
    received_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_goods_receipt_order_idempotency UNIQUE (purchase_order_id, idempotency_key)
);

CREATE TABLE goods_receipt_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id BIGINT NOT NULL REFERENCES goods_receipt(id),
    purchase_order_line_id BIGINT NOT NULL REFERENCES purchase_order_line(id),
    product_id VARCHAR(64) NOT NULL REFERENCES beer_product(id),
    received_baskets INTEGER NOT NULL,
    received_loose_units INTEGER NOT NULL,
    received_equivalent_units INTEGER NOT NULL,
    stock_movement_id BIGINT NULL REFERENCES stock_movement(id),
    CONSTRAINT ck_goods_receipt_line_baskets CHECK (received_baskets >= 0),
    CONSTRAINT ck_goods_receipt_line_loose_units CHECK (received_loose_units >= 0),
    CONSTRAINT ck_goods_receipt_line_received CHECK (received_equivalent_units > 0)
);

CREATE INDEX ix_purchase_order_supplier ON purchase_order (supplier_id);
CREATE INDEX ix_purchase_order_status ON purchase_order (status);
CREATE INDEX ix_purchase_order_line_order ON purchase_order_line (purchase_order_id);
-- El índice de la restricción UNIQUE también cubre goods_receipt.purchase_order_id.
CREATE INDEX ix_goods_receipt_received_at ON goods_receipt (received_at);

COMMIT;
